/**
 * Translated error texts (no imports, so `lib/i18n.ts` can load it without a cycle).
 * Matching logic lives in `lib/apiErrors.ts`.
 */
export type Lang = 'en' | 'fr' | 'es' | 'zh'
type Texts = Record<Lang, string>

export interface ErrorEntry extends Texts {
  /** Translation key, under `errors.` */
  key: string
  /** Exact backend messages (compared case-insensitively, trailing punctuation ignored). */
  messages?: string[]
  /** Backend messages that start with one of these. */
  prefixes?: string[]
  /** Backend messages matching this pattern. */
  pattern?: RegExp
  /** Names given to the pattern's capture groups, in order, for interpolation. */
  params?: string[]
  /** Backend error codes. Checked only when no message matched. */
  codes?: string[]
}

